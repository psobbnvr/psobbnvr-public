// grip_offset: rotation + translation in grip-local axes, labelled as the
// wearer feels them. Held thumb-up, the grip frame's -Z points up along
// the fist and the weapon extends along Y: pitch (tip up/down) = about X,
// roll (spin about the blade) = about Y, yaw (left/right) = about Z.
// Applied Rx*Ry*Rz (row-vector), then fwd_cm along -Z, up_cm along +Y,
// side_cm along +X (through the palm); cm scaled by world_scale.
inline D3DMATRIX GripOffsetMatrix(float pitch_deg, float roll_deg,
                                  float yaw_deg, float fwd_cm, float up_cm,
                                  float side_cm = 0.0f) {
    const float d2r = 3.14159265f / 180.0f;
    // Negated so positive pitch tips the blade/barrel up.
    const float p = -pitch_deg * d2r;
    const float ang_y = roll_deg * d2r;  // felt roll = about Y
    const float ang_z = yaw_deg * d2r;   // felt yaw = about Z
    D3DMATRIX rx = vrmod::Identity(), ry = vrmod::Identity(), rz = vrmod::Identity();
    rx._22 = cosf(p); rx._23 = sinf(p); rx._32 = -sinf(p); rx._33 = cosf(p);
    ry._11 = cosf(ang_y); ry._13 = -sinf(ang_y); ry._31 = sinf(ang_y); ry._33 = cosf(ang_y);
    rz._11 = cosf(ang_z); rz._12 = sinf(ang_z); rz._21 = -sinf(ang_z); rz._22 = cosf(ang_z);
    D3DMATRIX m = vrmod::Multiply(vrmod::Multiply(rx, ry), rz);
    const float cm = 0.01f * vrmod::config.world_scale;
    m._41 = side_cm * cm;
    m._42 = up_cm * cm;
    m._43 = -fwd_cm * cm;
    return m;
}

// The active tuple: guns have their own, separate from melee.
inline D3DMATRIX ActiveGripOffset() {
    if (current_is_gun)
        return GripOffsetMatrix(vrmod::config.gun_pitch_deg,
                                vrmod::config.gun_roll_deg,
                                vrmod::config.gun_yaw_deg,
                                vrmod::config.gun_fwd_cm,
                                vrmod::config.gun_up_cm);
    return GripOffsetMatrix(vrmod::config.grip_pitch_deg,
                            vrmod::config.grip_roll_deg,
                            vrmod::config.grip_yaw_deg,
                            vrmod::config.grip_fwd_cm,
                            vrmod::config.grip_up_cm);
}

// A hand's barrel ray (origin, unit forward, world units): the -Y axis
// (muzzle end) of the frame the gun is drawn in, grip tuple x hand world
// pose, so the ray is the visible barrel. pitch_trim_deg tilts it about
// the weapon's side axis, positive = toward world down. Works for either
// hand (the grip frames and tuples are mirror-symmetric). False with no
// pose or before the head pose is written this frame.
inline bool BarrelRay(int hand, float* origin, float* fwd,
                      float pitch_trim_deg) {
    D3DMATRIX pose, hand_world;
    if (!vrmod::Get()->GetHandPose(hand & 1, pose) ||
        !gamecam::WorldFromTracking(pose, hand_world))
        return false;
    const D3DMATRIX m = vrmod::Multiply(ActiveGripOffset(), hand_world);
    float f[3] = {-m._21, -m._22, -m._23};  // row 2 = the weapon's Y axis; muzzle on -Y
    float len = sqrtf(f[0] * f[0] + f[1] * f[1] + f[2] * f[2]);
    if (len < 1e-6f)
        return false;
    f[0] /= len; f[1] /= len; f[2] /= len;
    if (pitch_trim_deg != 0.0f) {
        // Side axis = row 1 (the weapon's X). t = side x fwd, signed so
        // positive trim tilts toward world down (-Y).
        float ax[3] = {m._11, m._12, m._13};
        const float al = sqrtf(ax[0] * ax[0] + ax[1] * ax[1] + ax[2] * ax[2]);
        if (al > 1e-6f) {
            ax[0] /= al; ax[1] /= al; ax[2] /= al;
            float t[3] = {ax[1] * f[2] - ax[2] * f[1],
                          ax[2] * f[0] - ax[0] * f[2],
                          ax[0] * f[1] - ax[1] * f[0]};
            if (t[1] > 0.0f) {
                t[0] = -t[0]; t[1] = -t[1]; t[2] = -t[2];
            }
            const float a = pitch_trim_deg * (3.14159265f / 180.0f);
            const float c = cosf(a), s = sinf(a);
            for (int i = 0; i < 3; i++)
                f[i] = f[i] * c + t[i] * s;
        }
    }
    fwd[0] = f[0]; fwd[1] = f[1]; fwd[2] = f[2];
    origin[0] = m._41; origin[1] = m._42; origin[2] = m._43;
    return true;
}

inline void ResetLearning() {
    learn_valid = false;
    learn_count = -1;
    settle = -1;
    split_index = -1;
    for (int i = 0; i < TWIN_MAX_PARTS; i++)
        max_dev[i] = 0.0f;
}

// Shared by both bracket hooks (funnel + composite entry). Returns whether
// this call owns the bracket (nested calls fold into the outer bracket).
inline bool BracketOpen(void* self, const char* which, bool left,
                        bool learns) {
    if (bracket_open)
        return false;
    bracket_open = true;
    bracket_is_left = left;
    bracket_learns = learns;
    bracket_fired = true;
    part_index = 0;
    return true;
}

inline void BracketClose() {
    bracket_open = false;
    // Twin-split learning, once per completed funnel bracket (composite
    // brackets split per bracket instead).
    if (!bracket_learns || !vrmod::config.twin_split || !current_twin_funnel ||
        split_index >= 0)
        return;
    if (!learn_valid) {
        if (part_index > 0) {
            learn_count = part_index;
            learn_valid = true;
        }
    } else if (part_index > 0 && part_index != learn_count) {
        // Part count changed (equip transition, effects): relearn.
        ResetLearning();
    } else if (settle >= 0 && settle-- == 0) {
        // Latch: walk back from the last part while it kept moving (the
        // off-hand half is a contiguous tail; part 0 never counts).
        int j = learn_count;
        while (j > 1 && max_dev[j - 1] > TWIN_DEV_LOW)
            j--;
        if (j > 1 && j < learn_count) {
            split_index = j;
            diag::Log("weapongrip: twin split latched at part %d of %d "
                      "(dev: %.3f %.3f %.3f %.3f %.3f %.3f)",
                      j, learn_count, max_dev[0], max_dev[1], max_dev[2],
                      max_dev[3], max_dev[4], max_dev[5]);
        } else {
            // No clean rigid head: not a twin (or not settled); start over.
            ResetLearning();
        }
    }
}

inline void __fastcall HookDraw(void* self, void* edx) {
    const bool owns = self != nullptr && self == current_weapon &&
                      BracketOpen(self, "funnel", false, true);
    original_draw(self, edx);
    if (owns)
        BracketClose();
}

// The composite entry (twin swords, mechguns): called once per half;
// odd brackets within a pass are the off-hand half.
inline void __fastcall HookCompDraw(void* self, void* edx) {
    bool owns = false;
    if (self != nullptr && self == current_weapon) {
        const bool left = vrmod::config.twin_split && current_twin_comp &&
                          (comp_ordinal & 1) != 0;
        owns = BracketOpen(self, "comp", left, false);
        if (owns)
            comp_ordinal++;
    }
    original_comp_draw(self, edx);
    if (owns)
        BracketClose();
}

// True when a trail render's `this` is the re-seated local weapon (the
// inline ribbon) or one of its trail-object slots.
inline bool SuppressTrail(void* self) {
    if (!have_grip || self == nullptr || current_weapon == nullptr)
        return false;
    if (self == current_weapon) {
        trails_suppressed++;
        return true;
    }
    const uintptr_t w = reinterpret_cast<uintptr_t>(current_weapon);
    for (int i = 0; i < WEAPON_TRAIL_SLOT_COUNT; i++) {
        const uintptr_t slot = w + WEAPON_TRAIL_SLOT_FIRST + i * 4;
        if (diag::Accessible(slot, 4, false) &&
            self == *reinterpret_cast<void* const*>(slot)) {
            trails_suppressed++;
            return true;
        }
    }
    return false;
}

inline void __fastcall HookTrailA(void* self, void* edx) {
    if (SuppressTrail(self))
        return;
    original_trail_a(self, edx);
}

inline void __fastcall HookTrailB(void* self, void* edx) {
    if (SuppressTrail(self))
        return;
    original_trail_b(self, edx);
}

// weapon_scale: uniform scale about the weapon root (the point pinned to
// the controller), applied to the part's root-space matrix.
inline D3DMATRIX ScaleRel(D3DMATRIX rel, float s) {
    rel._11 *= s; rel._12 *= s; rel._13 *= s;
    rel._21 *= s; rel._22 *= s; rel._23 *= s;
    rel._31 *= s; rel._32 *= s; rel._33 *= s;
    rel._41 *= s; rel._42 *= s; rel._43 *= s;
    return rel;
}

// Every device WORLD SetTransform on world-space passes. Returns true
// with the re-seated matrix in out.
inline bool SubstituteWorld(const D3DMATRIX& in, D3DMATRIX& out, bool boxed) {
    if (!bracket_open)
        return false;
    const int i = part_index++;
    // Equipment part matrices are rigid, so RigidInverse is exact.
    // The seat root: the first matrix is hand bone x the model's first
    // node, which some weapons rotate (the basic Partisans, the parasols,
    // Glide Divine). So the main hand seats on the weapon's attach bone
    // (WEAPON_ATTACH_BONE_OFFSET) when readable and near the first matrix,
    // else on the first matrix.
    if (i == 0) {
        D3DMATRIX root = in;
        if (!bracket_is_left) {
            bracket_root_raw = in;
            have_bracket_root_raw = true;
            const int attach = ReadAttachBone();
            const int seat_index = attach >= 0 ? attach : hand_bone_index;
            seat_attach_bone = seat_index;
            seat_on_fist = seat_index != hand_bone_index;
            D3DMATRIX bone;
            bool seated_on_bone = false;
            if (ArrayBoneWorld(seat_index, bone)) {
                float dist = 0.0f, deg = 0.0f;
                RigidDelta(in, bone, dist, deg);
                seated_on_bone = dist <= SEAT_BONE_MAX_UNITS;
                if (seated_on_bone)
                    root = bone;
                if (seat_logged_weapon != current_weapon) {
                    seat_logged_weapon = current_weapon;
                    diag::Log("seatbone: attach bone %d%s; first matrix sits %.2f units / %.1f deg off it -> %s",
                              seat_index,
                              seat_on_fist ? " (NOT the hand bone - fist rest lock + trim)" : " (the hand bone)",
                              dist, deg,
                              seated_on_bone ? "seating on the bone" : "too far, seating on the first matrix");
                }
            }
            // Hand-bone stash for the VR hands: the hand bone when the
            // weapon sits on another bone, else the seat root.
            D3DMATRIX hand;
            const bool have_hand =
                seat_on_fist && seated_on_bone && ArrayBoneWorld(hand_bone_index, hand);
            if (have_hand)
                vrmod::hand_bone_world_right = hand;
            else
                vrmod::hand_bone_world_right = root;
            vrmod::have_hand_bone_right = true;
            root_inv = vrmod::RigidInverse(root);
            // Fist rest lock (see fist_rest).
            if (have_hand) {
                const D3DMATRIX delta = vrmod::Multiply(root, vrmod::RigidInverse(hand));
                if (!fist_rest_locked) {
                    if (have_fist_prev_delta) {
                        float dd = 0.0f, ddeg = 0.0f;
                        RigidDelta(delta, fist_prev_delta, dd, ddeg);
                        fist_still_count = (dd <= FIST_LOCK_UNITS && ddeg <= FIST_LOCK_DEG)
                                               ? fist_still_count + 1 : 0;
                    }
                    fist_prev_delta = delta;
                    have_fist_prev_delta = true;
                    if (fist_still_count >= FIST_LOCK_BRACKETS) {
                        fist_rest = delta;
                        fist_rest_locked = true;
                        float rd = 0.0f, rdeg = 0.0f;
                        RigidDelta(root, hand, rd, rdeg);
                        diag::Log("seatbone: fist rest pose locked after %d still brackets (attach bone %.2f units / %.1f deg from the hand bone)",
                                  fist_still_count, rd, rdeg);
                    }
                }
                root_inv = vrmod::Multiply(root_inv, fist_rest_locked ? fist_rest : delta);
            }
        } else {
            root_inv = vrmod::RigidInverse(root);
        }
        // Composite off-hand brackets stash the left bone (the funnel
        // split stashes it at split_index below).
        bracket_drew = true;
        if (bracket_is_left) {
            vrmod::hand_bone_world_left = in;
            vrmod::have_hand_bone_left = true;
        }
    }
    // Twin-split learning (funnel brackets): track each part's drift from
    // its first-seen root-relative translation (part order is stable).
    if (bracket_learns && vrmod::config.twin_split && current_twin_funnel &&
        split_index < 0 && i < TWIN_MAX_PARTS && i > 0) {
        const D3DMATRIX rel = vrmod::Multiply(in, root_inv);
        if (!learn_valid) {
            first_rel[i][0] = rel._41;
            first_rel[i][1] = rel._42;
            first_rel[i][2] = rel._43;
        } else if (i < learn_count) {
            const float dx = rel._41 - first_rel[i][0];
            const float dy = rel._42 - first_rel[i][1];
            const float dz = rel._43 - first_rel[i][2];
            const float dev = sqrtf(dx * dx + dy * dy + dz * dz);
            if (dev > max_dev[i])
                max_dev[i] = dev;
            if (settle < 0 && dev > TWIN_DEV_HIGH)
                settle = TWIN_SETTLE_BRACKETS;
        }
    }
    // Boxed radar/menu passes use their own camera and keep the game's
    // matrices.
    if (boxed)
        return false;
    // Off-hand composite bracket: the whole bracket goes to the left grip,
    // rooted at its own first matrix; no left pose = game animation.
    if (bracket_is_left) {
        if (!have_left_grip)
            return false;
        D3DMATRIX rel = vrmod::Multiply(in, root_inv);
        if (vrmod::config.weapon_scale != 1.0f)
            rel = ScaleRel(rel, vrmod::config.weapon_scale);
        out = vrmod::Multiply(rel, grip_world_left);
        subst_sets_left++;
        return true;
    }
    // Off-hand tail: to the left grip, rooted at its own first part.
    if (split_index > 0 && i >= split_index) {
        if (i == split_index) {
            // Funnel-path twin: this part rides the left hand bone.
            vrmod::hand_bone_world_left = in;
            vrmod::have_hand_bone_left = true;
        }
        if (!have_left_grip)
            return false;
        if (i == split_index)
            left_root_inv = vrmod::RigidInverse(in);
        D3DMATRIX rel = vrmod::Multiply(in, left_root_inv);
        if (vrmod::config.weapon_scale != 1.0f)
            rel = ScaleRel(rel, vrmod::config.weapon_scale);
        out = vrmod::Multiply(rel, grip_world_left);
        subst_sets_left++;
        return true;
    }
    if (!have_grip)
        return false;
    D3DMATRIX rel = vrmod::Multiply(in, root_inv);
    if (vrmod::config.weapon_scale != 1.0f)
        rel = ScaleRel(rel, vrmod::config.weapon_scale);
    out = vrmod::Multiply(rel, seat_on_fist ? grip_world_fist : grip_world);
    subst_sets++;
    return true;
}

// Once per BeginScene pass, after gamecam::Apply (pose + anchor fresh).
inline void OnFrame() {
    bracket_open = false;
    part_index = 0;
    comp_ordinal = 0;
    bracket_fired_last_pass = bracket_fired;
    bracket_drew_last_pass = bracket_drew;
    bracket_drew = false;
    subst_sets_last_pass = subst_sets;
    subst_sets_left_last_pass = subst_sets_left;
    trails_suppressed_last_pass = trails_suppressed;
    bracket_fired = false;
    subst_sets = 0;
    subst_sets_left = 0;
    trails_suppressed = 0;


    // The weapon pointer (null bare-handed), re-read every pass, and its
    // classification.
    current_weapon = nullptr;
    current_category = 0;
    current_kind = WEAPON_KIND_NONE;
    current_is_gun = false;
    current_twin_funnel = false;
    current_twin_comp = false;
    current_projectile = 0;
    current_fire_override = 0;
    const uintptr_t entity = gamecam::ResolveEntity();
    if (entity != 0 && diag::Accessible(entity + PLAYER_WEAPON_SLOT, 4, false))
        current_weapon = *reinterpret_cast<void* const*>(entity + PLAYER_WEAPON_SLOT);
    if (current_weapon != nullptr) {
        const uintptr_t w = reinterpret_cast<uintptr_t>(current_weapon);
        if (diag::Accessible(w + WEAPON_CATEGORY_OFFSET, 1, false))
            current_category = *reinterpret_cast<const uint8_t*>(w + WEAPON_CATEGORY_OFFSET);
        if (diag::Accessible(w + WEAPON_PMT_OFFSET, 4, false)) {
            const uintptr_t pmt =
                *reinterpret_cast<const uintptr_t*>(w + WEAPON_PMT_OFFSET);
            if (pmt != 0 && diag::Accessible(pmt + PMT_PROJECTILE_OFFSET, 1, false))
                current_projectile =
                    *reinterpret_cast<const uint8_t*>(pmt + PMT_PROJECTILE_OFFSET);
        }
        if (diag::Accessible(w, 4, false)) {
            const uintptr_t vt = *reinterpret_cast<const uintptr_t*>(w);
            if (vt != 0 && diag::Accessible(vt + WEAPON_FIRE_OVERRIDE_OFFSET, 4, false))
                current_fire_override =
                    *reinterpret_cast<const uintptr_t*>(vt + WEAPON_FIRE_OVERRIDE_OFFSET);
        }
        current_kind = KindOfCategory(current_category);
        current_is_gun = KindIsGun(current_kind);
        // The twin split's kind gate.
        current_twin_funnel = KindSplitsFunnel(current_kind);
        current_twin_comp = KindSplitsComposite(current_kind);
    }
    if (current_weapon != logged_weapon) {
        logged_weapon = current_weapon;
        seat_attach_bone = -1;   // re-read at the new weapon's first bracket
        seat_on_fist = false;
        ResetFistLock();
        if (current_weapon != nullptr) {
            const bool old_rule = current_projectile != 0 ||
                                  IsKnownFiringOverride(current_fire_override);
            diag::Log("weapongrip: weapon %p class 0x%02X kind 0x%02X -> %s "
                      "(projectile %d fire override 0x%08X: old rule %s; "
                      "twin funnel=%d comp=%d)",
                      current_weapon, current_category, current_kind,
                      current_is_gun ? "GUN" : "melee", current_projectile,
                      (unsigned)current_fire_override,
                      old_rule == current_is_gun ? "agrees" : "DISAGREES",
                      current_twin_funnel ? 1 : 0, current_twin_comp ? 1 : 0);
        } else {
            diag::Log("weapongrip: bare hands");
        }
    }

    // Weapon changed: relearn the twin split.
    if (current_weapon != learn_weapon) {
        learn_weapon = current_weapon;
        ResetLearning();
    }

    // The hand-bone stash stays valid only while brackets keep drawing
    // (setting matrices, not just opening - see bracket_drew). The world
    // draws on alternating passes, so a 3-pass gap is allowed; longer
    // (unequip, menus, warps, towns) invalidates it.
    if (bracket_drew_last_pass)
        passes_since_bracket = 0;
    else if (passes_since_bracket < 100)
        passes_since_bracket++;
    if (current_weapon == nullptr || passes_since_bracket > 3) {
        vrmod::have_hand_bone_right = false;
        vrmod::have_hand_bone_left = false;
    }
    have_bracket_root_raw = false;

    // The grip target, once per pass; no pose or no takeover = no
    // substitution.
    have_grip = false;
    if (vrmod::config.weapon_grip && installed && gamecam::DrivesView()) {
        D3DMATRIX pose;
        if (vrmod::Get()->GetHandPose(1, pose)) {  // 1 = right hand
            D3DMATRIX hand_world;
            if (gamecam::WorldFromTracking(pose, hand_world)) {
                const D3DMATRIX offset = ActiveGripOffset();
                grip_world = vrmod::Multiply(offset, hand_world);
                grip_world_fist = vrmod::Multiply(
                    vrmod::Multiply(offset,
                                    GripOffsetMatrix(vrmod::config.fist_pitch_deg,
                                                     vrmod::config.fist_roll_deg,
                                                     vrmod::config.fist_yaw_deg,
                                                     vrmod::config.fist_fwd_cm,
                                                     vrmod::config.fist_up_cm,
                                                     vrmod::config.fist_side_cm)),
                    hand_world);
                have_grip = true;
            }
        }
    }
    // The off-hand grip, whenever a weapon is held (composite brackets need
    // it at once). Same tuple as the main hand: the grip frames are
    // mirrored and the tuples mirror-symmetric.
    have_left_grip = false;
    if (current_weapon != nullptr && vrmod::config.twin_split &&
        vrmod::config.weapon_grip && installed && gamecam::DrivesView()) {
        D3DMATRIX pose;
        if (vrmod::Get()->GetHandPose(0, pose)) {  // 0 = left hand
            D3DMATRIX hand_world;
            if (gamecam::WorldFromTracking(pose, hand_world)) {
                grip_world_left =
                    vrmod::Multiply(ActiveGripOffset(), hand_world);
                have_left_grip = true;
            }
        }
    }

    if (vrmod::config.weapon_grip != prev_enabled) {
        prev_enabled = vrmod::config.weapon_grip;
        if (vrmod::config.weapon_grip)
            log_budget = 8;
    }
    if (vrmod::config.weapon_grip && log_budget > 0) {
        log_budget--;
        diag::Log("weapongrip: weapon=%p cat=0x%02X gun=%d grip=%d gripL=%d split=%d drives=%d fired_last=%d sets_last=%d setsL_last=%d trails_last=%d",
                  current_weapon, current_category, current_is_gun ? 1 : 0,
                  have_grip ? 1 : 0, have_left_grip ? 1 : 0, split_index,
                  gamecam::DrivesView() ? 1 : 0,
                  bracket_fired_last_pass ? 1 : 0, subst_sets_last_pass,
                  subst_sets_left_last_pass, trails_suppressed_last_pass);
    }
}

// Called from the first BeginScene; installs unconditionally, behaviour is
// gated at call time.
inline void Install() {
    static bool tried = false;
    if (tried)
        return;
    tried = true;

    MH_STATUS status = MH_Initialize();
    if (status != MH_OK && status != MH_ERROR_ALREADY_INITIALIZED) {
        probe::Log("weapongrip: MH_Initialize failed (%d)", (int)status);
        return;
    }
    if (MH_CreateHook(reinterpret_cast<void*>(WEAPON_HELD_DRAW),
                      reinterpret_cast<void*>(&HookDraw),
                      reinterpret_cast<void**>(&original_draw)) != MH_OK ||
        MH_CreateHook(reinterpret_cast<void*>(WEAPON_COMP_DRAW),
                      reinterpret_cast<void*>(&HookCompDraw),
                      reinterpret_cast<void**>(&original_comp_draw)) != MH_OK ||
        MH_CreateHook(reinterpret_cast<void*>(TRAIL_RENDER_A),
                      reinterpret_cast<void*>(&HookTrailA),
                      reinterpret_cast<void**>(&original_trail_a)) != MH_OK ||
        MH_CreateHook(reinterpret_cast<void*>(TRAIL_RENDER_B),
                      reinterpret_cast<void*>(&HookTrailB),
                      reinterpret_cast<void**>(&original_trail_b)) != MH_OK) {
        probe::Log("weapongrip: MH_CreateHook failed");
        return;
    }
    if (MH_EnableHook(reinterpret_cast<void*>(WEAPON_HELD_DRAW)) != MH_OK ||
        MH_EnableHook(reinterpret_cast<void*>(WEAPON_COMP_DRAW)) != MH_OK ||
        MH_EnableHook(reinterpret_cast<void*>(TRAIL_RENDER_A)) != MH_OK ||
        MH_EnableHook(reinterpret_cast<void*>(TRAIL_RENDER_B)) != MH_OK) {
        probe::Log("weapongrip: MH_EnableHook failed");
        return;
    }
    installed = true;
    probe::Log("weapongrip: held-weapon draw brackets (funnel 0x%08X + composite 0x%08X) + trail hooks installed (0x%08X / 0x%08X)",
               (unsigned)WEAPON_HELD_DRAW, (unsigned)WEAPON_COMP_DRAW,
               (unsigned)TRAIL_RENDER_A, (unsigned)TRAIL_RENDER_B);
}

