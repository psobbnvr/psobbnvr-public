// The equipped weapon rides the controller grip pose.
//
// Each equipped item is its own render object (weapons: one class per
// category, ~140, created via the factory table at 0x9C2240 on item
// data[1]). The player entity holds them in a pointer array at +0xDF8
// indexed by the object's slot byte (+0x188): weapon = slot 6 =
// entity+0xE10 (mag slot 1, armor/shield slot 2). The shared base draw
// virtual (vtbl+0x08 = 0x5C4068: hide flag byte +0xF1, then 0x5C407C ->
// NJ model draw 0x83046C) is the on-the-floor representation and draws
// nothing for the held weapon. The held weapon draws through +0x60
// (0x5E8020) and +0x68 (0x5E88CC), which both funnel into 0x5E8088
// (thiscall, this = the weapon object). While that runs with this ==
// [entity+0xE10], every WORLD SetTransform belongs to the weapon.
//
// Re-seat: for each bracketed matrix, rel = part_world x inverse(root)
// (root = the bracket's first matrix, or the attach bone), and the
// substituted world = rel x grip_offset x WorldFromTracking(right hand
// pose). With no hand pose this frame nothing is substituted and the
// weapon follows the game's animation. Bracketed draws are exempt from
// head-trim suppression and body culling (ExemptingDraws()).
//
// Two-handed weapons: (1) the composite held-model draw 0x5E84A8 draws
// one half per call for twin swords and mechguns; halves alternate
// main/off, so odd composite brackets go to the left grip. (2) Funnel
// duals (daggers, knuckles) draw both halves in one bracket; the off-hand
// tail is found by its parts drifting against the root (same-hand parts
// hold within +-0.002 units) and goes to the left grip. Both only for
// two-handed kinds ([vr] twin_split).
//
// [vr] weapon_grip, weapon_scale (uniform scale about the grip, re-seated
// draws only).
