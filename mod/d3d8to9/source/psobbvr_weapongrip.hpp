// The character's hand bone (the weapon seat and the hands' frame): the
// entity's bone matrix array at entity+0xE0 (64 bytes per bone);
// bone[hand_bone_index] x the global root matrix [0xA48980] = the hand's
// world matrix. Bone 48 on every model checked; hands.hpp re-confirms.
constexpr uintptr_t ENTITY_BONES_OFFSET = 0xE0;
constexpr uintptr_t GLOBAL_ROOT_MATRIX = 0x00A48980;
inline int hand_bone_index = 48;
inline bool ArrayBoneWorld(int i, D3DMATRIX& out) {
    const uintptr_t entity = gamecam::ResolveEntity();
    if (entity == 0 || !diag::Accessible(entity + ENTITY_BONES_OFFSET, 4, false))
        return false;
    const uintptr_t bones = *reinterpret_cast<const uintptr_t*>(entity + ENTITY_BONES_OFFSET);
    const uintptr_t m = bones + (uintptr_t)i * 64;
    if (bones == 0 || i < 0 || !diag::Accessible(m, 64, false) ||
        !diag::Accessible(GLOBAL_ROOT_MATRIX, 64, false))
        return false;
    out = vrmod::Multiply(*reinterpret_cast<const D3DMATRIX*>(m),
                          *reinterpret_cast<const D3DMATRIX*>(GLOBAL_ROOT_MATRIX));
    return true;
}
// Rigid delta between two world matrices: translation distance and the
// rotation angle of a x inverse(b).
inline void RigidDelta(const D3DMATRIX& a, const D3DMATRIX& b, float& dist, float& deg) {
    const D3DMATRIX d = vrmod::Multiply(a, vrmod::RigidInverse(b));
    dist = sqrtf(d._41 * d._41 + d._42 * d._42 + d._43 * d._43);
    float c = (d._11 + d._22 + d._33 - 1.0f) * 0.5f;
    if (c > 1.0f) c = 1.0f;
    if (c < -1.0f) c = -1.0f;
    deg = acosf(c) * 180.0f / 3.14159265f;
}
