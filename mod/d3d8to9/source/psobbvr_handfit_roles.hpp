// The row for a class and hand (0 = left, 1 = right), or null.
inline const RoleRow* Find(int class_id, int side) {
    for (const RoleRow& r : kRows)
        if (r.class_id == class_id && r.side == side)
            return &r;
    return nullptr;
}

// The length of (x, y, z) as JavaScript's Math.hypot computes it (scaled by
// the largest part, compensated sum): the tables were generated with it, so
// a web point's nearest block is decided on the same numbers.
inline double Hypot3(double x, double y, double z) {
    const double a[3] = {std::fabs(x), std::fabs(y), std::fabs(z)};
    double m = 0.0;
    for (double v : a)
        if (v > m)
            m = v;
    if (m == 0.0)
        return 0.0;
    double sum = 0.0, compensation = 0.0;
    for (double v : a) {
        const double n = v / m;
        const double summand = n * n - compensation;
        const double preliminary = sum + summand;
        compensation = (preliminary - sum) - summand;
        sum = preliminary;
    }
    return std::sqrt(sum) * m;
}

// The roles of a row's points for a keep tolerance (cm) and world scale
// (game units per metre), written to out[0 .. point_count - 1], by the rule
// at the top of this file.
inline void ResolveRoles(const RoleRow& row, double keep_tol_cm, double world_scale, Role* out) {
    const int n = row.point_count <= kMaxPoints ? row.point_count : kMaxPoints;
    const double threshold = row.knuckle_y - keep_tol_cm * (0.01 * world_scale);
    bool web[kMaxPoints] = {};
    for (int v = 0; v < n; ++v) {
        const RolePoint& p = row.points[v];
        out[v] = Role::Kept;
        switch (p.lobe) {
        case Lobe::Thumb:
            out[v] = Role::Thumb;
            break;
        case Lobe::Index:
        case Lobe::Outer:
        case Lobe::Web:
            if (p.y >= threshold)
                break;
            if (p.lobe == Lobe::Index)
                out[v] = Role::Index;
            else if (p.lobe == Lobe::Outer)
                out[v] = Role::Outer;
            else
                web[v] = true;   // stays Kept until resolved below
            break;
        default:
            break;
        }
    }
    for (int v = 0; v < n; ++v) {
        if (!web[v])
            continue;
        const RolePoint& p = row.points[v];
        Role best = Role::Kept;
        double best_d = INFINITY;
        for (int w = 0; w < n; ++w) {
            if (out[w] != Role::Index && out[w] != Role::Outer)
                continue;
            const RolePoint& q = row.points[w];
            const double d = Hypot3(p.x - q.x, p.y - q.y, p.z - q.z);
            if (d < best_d) {
                best_d = d;
                best = out[w];
            }
        }
        out[v] = best;
    }
}

